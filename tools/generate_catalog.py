"""Validate the curated ingredient list and generate the PostgreSQL seed SQL."""
from pathlib import Path
import csv
import json
import sys
if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from tools.appearance import SHAPES, COLORS

ROOT = Path(__file__).resolve().parents[1]


def build(source: Path) -> str:
    with source.open(encoding='utf-8', newline='') as file:
        reader = csv.DictReader(file)
        if reader.fieldnames != ['name', 'category', 'unit', 'container_shape', 'container_color']:
            raise ValueError('Expected name,category,unit,container_shape,container_color columns')
        rows = list(reader)
    seen = set()
    values = []
    for line, row in enumerate(rows, 2):
        name, category, unit = (row[key].strip() for key in ('name', 'category', 'unit'))
        shape, color = row['container_shape'].strip(), row['container_color'].strip()
        key = name.casefold()
        if not name or not category or unit not in ('ml', 'piece') or key in seen or shape not in SHAPES or color not in COLORS:
            raise ValueError(f'Invalid or duplicate ingredient on line {line}')
        seen.add(key)
        quote = lambda value: "'" + value.replace("'", "''") + "'"
        values.append('  (' + ', '.join(map(quote, (name, category, unit, shape, color))) + ')')
    if len(values) < 200:
        raise ValueError('Catalog must contain at least 200 ingredients')
    retired = json.loads((ROOT / 'data' / 'retired_catalog_names.json').read_text(encoding='utf-8'))
    if not isinstance(retired, list) or any(not isinstance(name, str) or not name.strip() or name.casefold() in seen for name in retired):
        raise ValueError('Retired names must be nonempty strings absent from the active catalog')
    # Catalog rows are suggestions only: inventory and recipes store their own IDs.
    # Remove only the explicit historical placeholders, never arbitrary/custom rows.
    cleanup = 'delete from catalog where name in (' + ', '.join(quote(name) for name in retired) + ');\n' if retired else ''
    return '-- Generated by tools/generate_catalog.py; do not edit by hand.\n' + cleanup + 'insert into catalog (name, category, unit, container_shape, container_color) values\n' + ',\n'.join(values) + '\non conflict (name) do update set category = excluded.category, unit = excluded.unit, container_shape = excluded.container_shape, container_color = excluded.container_color;\n'


if __name__ == '__main__':
    try:
        output = build(ROOT / 'data' / 'ingredients.csv')
        (ROOT / 'backend' / 'seed.sql').write_text(output, encoding='utf-8')
        print('Generated backend/seed.sql')
    except (ValueError, OSError) as error:
        print(error, file=sys.stderr)
        sys.exit(1)
